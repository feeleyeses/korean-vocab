import { chromium } from 'playwright';
const url=process.env.KWF_URL||'https://feeleyeses.github.io/korean-vocab/';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900}});
await page.goto(`${url}?review35=${Date.now()}`,{waitUntil:'networkidle',timeout:60000});
await page.waitForFunction(()=>window.__KWF_UI_V35_READY__===true,{timeout:10000});
const click=async loc=>loc.evaluate(el=>el.click());
const openLearned=page.getByRole('button',{name:/打开已学词库|查看已学词库/}).first();
await click(openLearned); await page.waitForTimeout(250);
const full=page.locator('#review .review-module-grid article').filter({hasText:'全量库'}).first().locator('button');
if(!await full.count()||await full.isDisabled())throw new Error('全量库复习入口不可用');
await click(full); await page.waitForTimeout(350);
await page.waitForSelector('#study-card.review-mode .review-question');
const initial=await page.locator('#study-card').evaluate(card=>{
 const cr=card.getBoundingClientRect(),g=card.querySelector('.review-question>div'),gr=g.getBoundingClientRect(),bs=[...g.querySelectorAll(':scope>button')].map(b=>b.getBoundingClientRect());
 return {cardW:cr.width,gridW:gr.width,left:gr.left-cr.left,right:cr.right-gr.right,count:bs.length,widths:bs.map(x=>x.width)};
});
if(initial.count!==4)throw new Error(`复习选项不是4个: ${JSON.stringify(initial)}`);
if(initial.left>25||initial.right>25)throw new Error(`复习选项没有在X轴拉宽: ${JSON.stringify(initial)}`);
if(Math.max(...initial.widths)-Math.min(...initial.widths)>2)throw new Error(`复习选项宽度不统一: ${JSON.stringify(initial)}`);
await click(page.locator('#study-card .review-question>div>button').first()); await page.waitForTimeout(350);
const details=page.locator('#study-card details.answer-map');
await details.locator('summary').click(); await page.waitForTimeout(250);
const reveal=await page.locator('#study-card').evaluate(card=>{
 const cr=card.getBoundingClientRect(),c=card.querySelector('.continue').getBoundingClientRect(),map=card.querySelector('details.answer-map[open]'),mr=map.getBoundingClientRect(),list=map.querySelector('.option-map-list'),arts=[...list.querySelectorAll(':scope>article')];
 return {continueW:c.width,continueLeft:c.left-cr.left,continueRight:cr.right-c.right,mapCount:arts.length,mapRows:new Set(arts.map(a=>Math.round(a.getBoundingClientRect().top))).size,mapVisible:arts.map(a=>{const r=a.getBoundingClientRect();return r.width>40&&r.height>40&&r.top>=mr.top&&r.bottom<=mr.bottom&&r.left>=mr.left&&r.right<=mr.right}),scroll:list.scrollHeight,client:list.clientHeight};
});
if(reveal.continueLeft>25||reveal.continueRight>25)throw new Error(`继续按钮没有在X轴拉宽: ${JSON.stringify(reveal)}`);
if(reveal.mapCount!==4||reveal.mapRows!==2||!reveal.mapVisible.every(Boolean))throw new Error(`对应韩文未完整显示4项: ${JSON.stringify(reveal)}`);
if(reveal.scroll>reveal.client+2)throw new Error(`对应韩文发生内部滚动: ${JSON.stringify(reveal)}`);
console.log('PASS review v3.5 x-axis width + 4 mapping cards',JSON.stringify({initial,reveal}));
await browser.close();
