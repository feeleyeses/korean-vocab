await page.goto(base+'?qa='+Date.now(),{waitUntil:'networkidle'});
const nav=page.locator(width===390?'.mobile-nav':'.topbar nav');
assert.equal(await nav.locator('button').count(),width===390?4:5);
if(width!==390)assert.equal(await nav.locator('.active').innerText(),'首页');
assert.ok((await page.getByRole('heading',{name:'开始你的学习'}).boundingBox()).y<(await page.getByRole('heading',{name:'TOPIK 学习进度'}).boundingBox()).y);
