near((await page.locator('.continue').boundingBox()).y,continued.y,'long knowledge rail Y');
assert.ok(await page.locator('.knowledge-scroll').evaluate(el=>el.scrollHeight>el.clientHeight),'knowledge scroll');
await page.locator('.knowledge-scroll').evaluate(el=>{el.lastElementChild.remove();el.scrollTop=0;});
