import { chromium } from 'playwright';
const url=process.env.KWF_URL||'https://feeleyeses.github.io/korean-vocab/';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900}});
await page.goto(`${url}?v36=${Date.now()}`,{waitUntil:'networkidle',timeout:60000});
await page.waitForFunction(()=>window.__KWF_UI_V36_READY__===true,{timeout:10000});
const click=async l=>l.evaluate(el=>el.click());
const openLearned=page.getByRole('button',{name:/打开已学词库|查看已学词库/}).first();
await click(openLearned); await page.waitForTimeout(250);
const full=page.locator('#review .review-module-grid article').filter({hasText:'全量库'}).first().locator('button');
if(!await full.count()||await full.isDisabled())throw new Error('全量库复习入口不可用');
await click(full); await page.waitForTimeout(400);
const g=await page.locator('#study-card').evaluate(card=>{
  const r=card.getBoundingClientRect();
  const grid=card.querySelector('.review-question > div');
  const gr=grid?.getBoundingClientRect();
  const buttons=grid?[...grid.querySelectorAll(':scope > button')].map(b=>b.getBoundingClientRect()):[];
  return {version:card.dataset.kwfReviewGeometry,width:Math.round(r.width),leftGap:gr?Math.round(gr.left-r.left):null,rightGap:gr?Math.round(r.right-gr.right):null,buttonWidths:buttons.map(x=>Math.round(x.width))};
});
console.log('GEOMETRY',JSON.stringify(g));
if(g.version!=='v3.6-wide-x')throw new Error(`v3.6未生效: ${g.version}`);
if(g.width<700)throw new Error(`复习卡仍未沿X轴加宽: ${g.width}px`);
if(g.buttonWidths.length!==4||Math.min(...g.buttonWidths)<300)throw new Error(`复习按钮仍过窄: ${JSON.stringify(g.buttonWidths)}`);
console.log('PASS review card widened on x-axis',g);
await browser.close();
